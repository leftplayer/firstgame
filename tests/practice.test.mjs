import test from 'node:test';
import assert from 'node:assert/strict';
import {prepareArticle,validPrefix} from '../web/practice.js';
import {TypingSession} from '../assets/scripts/TypingSession.ts';
test('Chinese validates text including punctuation',()=>{assert.equal(prepareArticle({text:'风穿过，窗边。'}).target,'风穿过，窗边。');});
test('continuous Chinese commit stops at first wrong character',()=>{assert.deepEqual(validPrefix('风穿错窗边','风穿过窗边'),{value:'风穿',wrong:true});});
test('correct continuous Chinese input is accepted',()=>{assert.deepEqual(validPrefix('风穿过','风穿过窗边'),{value:'风穿过',wrong:false});});
test('wrong first letter cannot advance',()=>{assert.deepEqual(validPrefix('xbc','abc'),{value:'',wrong:true});});
test('deletion and correction work',()=>{assert.equal(validPrefix('a','abc').value,'a');assert.equal(validPrefix('ab','abc').value,'ab');});
test('timer includes preedit duration and does not restart at commit',()=>{const s=new TypingSession('风');s.start(1000);s.start(2000);assert.equal(s.seconds(3000),2);s.input('风',4000);assert.equal(s.seconds(9999),3);});
